export const LANGS = Object.keys(dict);

function detect() {
  try { const saved = localStorage.getItem("settleup.lang"); if (saved && dict[saved]) return saved } catch { }
  const nav = (navigator.languages || [navigator.language || "en"]).map(l => l.toLowerCase());
  for (const l of nav) {
    if (l.startsWith("zh")) return "zh-Hant";
    if (l.startsWith("en")) return "en";
  }
  return "en";
}

export let lang = detect();

export function t(key, vars = {}) {
  let s = dict[lang]?.[key] ?? dict.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

// Locale for numbers, currencies and dates
export const locale = () => lang === "zh-Hant" ? (navigator.language?.toLowerCase().startsWith("zh-hk") ? "zh-HK" : "zh-TW") : (navigator.language || "en");

export function setLang(l) {
  if (!dict[l]) return;
  lang = l;
  try { localStorage.setItem("settleup.lang", l) } catch { }
  applyStatic();
}

// Translate everything in the page marked with data-i18n / data-i18n-ph
export function applyStatic() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => el.textContent = t(el.dataset.i18n));
  document.querySelectorAll("[data-i18n-ph]").forEach(el => el.placeholder = t(el.dataset.i18nPh));
}
